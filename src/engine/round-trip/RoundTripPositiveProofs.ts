/**
 * SECP Industrial OS v3 — PROMPT-055: UI-to-Backend Round Trip Positive Proofs
 * Proves that valid engineering operations complete a full loop:
 * UI Intent -> Dispatcher -> Kernel -> Validation -> Sync Projection -> UI Truth.
 */

import { EngineeringDocument } from '../cad-kernel/document/CADDocument';
import { StateSyncEngine } from '../sync/StateSyncEngine';
import { RoundTripCoordinator } from './RoundTripCoordinator';

export interface RoundTripPositiveProofResult {
  proofId: string;
  name: string;
  passed: boolean;
  expectedBehavior: string;
  actualBehavior: string;
  details: string;
}

export interface RoundTripPositiveProofReport {
  timestamp: string;
  totalCount: number;
  passCount: number;
  allPassed: boolean;
  results: RoundTripPositiveProofResult[];
}

export class RoundTripPositiveProofs {
  public static async executeAllPositiveProofs(): Promise<RoundTripPositiveProofReport> {
    const timestamp = new Date().toISOString();
    const results: RoundTripPositiveProofResult[] = [];
    const syncEngine = StateSyncEngine.getInstance();

    const baseDoc: EngineeringDocument = {
      documentId: 'DOC-RT-POS',
      revision: 10,
      units: { system: 'SI_MM', length: 'mm', mass: 'kg', force: 'N', pressure: 'MPa', angle: 'deg' },
      sketches: [{ id: 'SK-1', name: 'Profile', plane: 'XY', entities: [] }],
      constraints: [],
      features: [{ id: 'F-1', featureId: 'F-1', name: 'Base', type: 'EXTRUDE', parameters: { depth: 50 } }],
      parameters: [{ id: 'P-1', name: 'Depth', value: 50, unit: 'mm' }],
      topologyMap: { version: 10, faceMap: { F1: 'TOPOLOGY_FACE_1' } },
      derived: { mesh: { vertices: new Float32Array(9), normals: new Float32Array(9), indices: new Uint32Array(3) } as any },
      evidence: [{
        evidenceId: 'EV-10',
        stage: 'GEOMETRY',
        sourceSystem: 'CADKernel',
        documentId: 'DOC-RT-POS',
        revision: 10,
        canonicalHash: '0xHASH_10',
        verdict: 'VALID'
      }]
    };

    syncEngine.reset();
    syncEngine.registerDocument(baseDoc);

    // 1. RT-POS-001 & RT-POS-002: Full Round Trip
    await (async () => {
      const intent: any = { toolId: 'FEATURE_EXTRUDE', documentId: 'DOC-RT-POS', parameters: { sketchId: 'SK-1', depth: 25, operation: 'JOIN', sketchEntities: [{x:0, y:0}, {x:20, y:0}, {x:20, y:20}, {x:0, y:20}] } };
      const res = await RoundTripCoordinator.executeRoundTrip('RT-POS-001', intent, baseDoc);

      const passed =
        res.roundTripVerdict === 'PASS' &&
        res.afterRevision === 11 &&
        res.uiProjectionRevision === 11 &&
        res.uiStatus === 'VALIDATED'; // From successful DocumentEvaluator

      results.push({
        proofId: 'RT-POS-001',
        name: 'Full Canonical Round Trip (Intent -> Projection)',
        passed,
        expectedBehavior: 'Valid extrusion intent must complete round trip and produce synchronized UI projections.',
        actualBehavior: `verdict=${res.roundTripVerdict}, rev=${res.afterRevision}, status=${res.uiStatus}`,
        details: 'Extrude capability completed end-to-end round trip.'
      });
    })();

    // 2. RT-POS-005: Feature Tree Round Trip
    await (async () => {
      const activeDoc = syncEngine.getSnapshot('DOC-RT-POS') ? syncEngine.activeDocuments.get('DOC-RT-POS')! : baseDoc;
      const intent: any = { toolId: 'FEATURE_EXTRUDE', documentId: 'DOC-RT-POS', parameters: { sketchId: 'SK-2', depth: 30, operation: 'JOIN', sketchEntities: [{x:100, y:100}, {x:130, y:100}, {x:130, y:130}, {x:100, y:130}] } };
      const res = await RoundTripCoordinator.executeRoundTrip('RT-POS-005', intent, activeDoc);

      const passed =
        res.roundTripVerdict === 'PASS' &&
        res.uiFeatureState &&
        res.uiFeatureState.length > activeDoc.features.length &&
        res.uiFeatureState[res.uiFeatureState.length - 1].type === 'EXTRUDE';

      if (!passed) {
        console.log(`RT-POS-005 FAILED: verdict=${res.roundTripVerdict}, uiLen=${res.uiFeatureState?.length}, docLen=${activeDoc.features.length}, err=${res.errorMessage}`);
      }

      results.push({
        proofId: 'RT-POS-005',
        name: 'Feature Tree Projection Matches Canonical Output',
        passed,
        expectedBehavior: 'UI Feature Tree must perfectly reflect canonical features generated by kernel.',
        actualBehavior: `features=${res.uiFeatureState?.length}, verdict=${res.roundTripVerdict}, err=${res.errorMessage}`,
        details: 'Feature tree synced perfectly.'
      });
    })();

    // 3. RT-POS-004: Viewport Geometry Round Trip
    await (async () => {
      const activeDoc = syncEngine.getSnapshot('DOC-RT-POS') ? syncEngine.activeDocuments.get('DOC-RT-POS')! : baseDoc;
      const intent: any = { toolId: 'FEATURE_EXTRUDE', documentId: 'DOC-RT-POS', parameters: { sketchId: 'SK-3', depth: 40, operation: 'JOIN', sketchEntities: [{x:200, y:200}, {x:240, y:200}, {x:240, y:240}, {x:200, y:240}] } };
      const res = await RoundTripCoordinator.executeRoundTrip('RT-POS-004', intent, activeDoc);

      const passed =
        res.roundTripVerdict === 'PASS' &&
        res.uiViewportState &&
        res.uiViewportState.documentRevision === res.afterRevision &&
        res.uiViewportState.bRepHash === res.afterGeometrySignature;

      if (!passed) {
        console.log(`RT-POS-004 FAILED: verdict=${res.roundTripVerdict}, uiViewportState=${!!res.uiViewportState}, bRepHash=${res.uiViewportState?.bRepHash}, afterGeom=${res.afterGeometrySignature}, err=${res.errorMessage}`);
      }

      results.push({
        proofId: 'RT-POS-004',
        name: 'Viewport Matches Canonical Geometry Projection',
        passed,
        expectedBehavior: 'Viewport state must securely bind to the canonical geometry hash produced by the kernel.',
        actualBehavior: `viewportRev=${res.uiViewportState?.documentRevision}, hash=${res.uiViewportState?.bRepHash}`,
        details: 'Viewport perfectly matched canonical geometry.'
      });
    })();

    const passCount = results.filter(r => r.passed).length;
    const totalCount = results.length;

    return {
      timestamp,
      totalCount,
      passCount,
      allPassed: passCount === totalCount,
      results
    };
  }
}
