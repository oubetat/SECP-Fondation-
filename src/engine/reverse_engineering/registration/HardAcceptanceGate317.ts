/**
 * PHASE 29 — REVERSE ENGINEERING
 * PATCH-317 — Registration / Alignment Engine
 * Hard Acceptance Gate 317 — Test Suite & Verification Battery
 * 
 * Verifies all 20 mandatory acceptance criteria for non-destructive point cloud registration,
 * SVD Procrustes closed-form solver, ICP iterative alignment, matrix orthogonality & scale = 1.0 invariants,
 * residual distribution metrics, Evidence Bus emission, and multi-scan pose graphs.
 */

import { PointCloudImportService } from '../point_cloud/PointCloudImportService';
import { PointCloudFilterEngine } from '../filtering/PointCloudFilterEngine';
import { PointCloudRegistrationEngine } from './PointCloudRegistrationEngine';
import { RigidTransformSolver317 } from './RigidTransformSolver317';
import { IterativeClosestPointSolver317 } from './IterativeClosestPointSolver317';
import { EvidenceBus314 } from '../../engineering_ai/copilot/EvidenceBus314';
import { Point3D } from '../point_cloud/PointCloudTypes315';
import { PointCorrespondence, RigidTransform } from './PointCloudRegistrationTypes317';

export interface GateTestResult317 {
  assertionId: number;
  description: string;
  passed: boolean;
  details: string;
}

export class HardAcceptanceGate317 {
  private importService: PointCloudImportService;
  private filterEngine: PointCloudFilterEngine;
  private registrationEngine: PointCloudRegistrationEngine;
  private evidenceBus: EvidenceBus314;

  constructor() {
    this.importService = PointCloudImportService.getInstance();
    this.filterEngine = PointCloudFilterEngine.getInstance();
    this.registrationEngine = PointCloudRegistrationEngine.getInstance();
    this.evidenceBus = EvidenceBus314.getInstance();
  }

  public runAllAssertions(): {
    passed: boolean;
    totalAssertions: number;
    passedCount: number;
    failedCount: number;
    results: GateTestResult317[];
  } {
    const results: GateTestResult317[] = [];

    const test = (id: number, desc: string, condition: boolean, details: string) => {
      results.push({
        assertionId: id,
        description: desc,
        passed: condition,
        details
      });
    };

    this.importService.clearAll();
    this.filterEngine.clearAll();
    this.registrationEngine.clearAll();
    this.evidenceBus.clearStore();

    // Setup Test Datasets: Anchor Target Cloud & Shifted/Rotated Source Cloud
    const targetPoints: Point3D[] = [
      { x: 0, y: 0, z: 0 },
      { x: 50, y: 0, z: 0 },
      { x: 50, y: 50, z: 0 },
      { x: 0, y: 50, z: 0 },
      { x: 25, y: 25, z: 40 },
      { x: 10, y: 20, z: 15 }
    ];

    // True Known Transformation: Translation (+12, -8, +25), Rotation 90 deg around Z
    // x' = -y + 12, y' = x - 8, z' = z + 25
    const knownR: [number, number, number, number, number, number, number, number, number] = [
      0, -1, 0,
      1,  0, 0,
      0,  0, 1
    ];
    const knownT: [number, number, number] = [12, -8, 25];
    const knownTransform = RigidTransformSolver317.buildTransform(knownR, knownT, 'KNOWN_SRC', 'KNOWN_TGT');

    // Source points generated by applying inverse or forward transform to create correspondences
    const sourcePoints: Point3D[] = targetPoints.map(tp => ({
      x: tp.x,
      y: tp.y,
      z: tp.z
    }));

    // Correspondences for SVD Test
    const correspondences: PointCorrespondence[] = targetPoints.map((tp, idx) => {
      const transformed = RigidTransformSolver317.transformPoint(sourcePoints[idx], knownTransform);
      return {
        sourcePointIndex: idx,
        targetPointIndex: idx,
        sourcePoint: [sourcePoints[idx].x, sourcePoints[idx].y, sourcePoints[idx].z],
        targetPoint: [transformed.x, transformed.y, transformed.z],
        distanceMm: 0,
        weight: 1.0,
        confidence: 1.0,
        rejected: false
      };
    });

    // 1. SVD Closed-Form Rigid Transformation Recovery
    const svdRes = RigidTransformSolver317.solveProcrustesSVD(correspondences);

    test(1, 'SVD Closed-Form Rigid Transformation Recovery (Procrustes Algorithm)',
      svdRes.rmseMm < 1e-3 && svdRes.transform.isValidRigid,
      `SVD solved exact rigid transform with RMSE: ${svdRes.rmseMm.toFixed(6)} mm`
    );

    // 2. Rigid Scale Invariant (Rule 11 & 14: Scale = 1.0)
    test(2, 'Rigid Transform Scale Invariant (Rule 11 & 14: Scale = 1.0)',
      svdRes.transform.scaleFactor === 1.0 && Math.abs(svdRes.transform.determinantR - 1.0) < 1e-4,
      `Scale factor strictly ${svdRes.transform.scaleFactor}, Det(R) = ${svdRes.transform.determinantR}`
    );

    // 3. Matrix Orthogonality & Determinant Check (Rule 53)
    const orthErr = RigidTransformSolver317.calculateOrthogonalityError(svdRes.transform.rotationMatrix);

    test(3, 'Matrix Orthogonality & Determinant (Rule 53: R^T * R = I)',
      orthErr < 1e-4,
      `Orthogonality Frobenius Error ||R^T * R - I|| = ${orthErr.toExponential(3)}`
    );

    // 4. Raw Point Cloud Immutability Test (Rule 2 & 3)
    const originalX = sourcePoints[0].x;
    RigidTransformSolver317.transformPoint(sourcePoints[0], knownTransform);

    test(4, 'Raw Point Cloud Immutability (Rule 2 & 3: Input arrays never modified)',
      sourcePoints[0].x === originalX,
      `Source point coordinate preserved at x = ${sourcePoints[0].x}`
    );

    // 5. ICP Deterministic Convergence on Shifted Scans
    const shiftedSource: Point3D[] = targetPoints.map(p => ({
      x: p.x + 2.0,
      y: p.y - 1.5,
      z: p.z + 0.5
    }));

    const icpRes = IterativeClosestPointSolver317.executeICP(shiftedSource, targetPoints, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'FINE',
      maxIterations: 30,
      maxCorrespondenceDistanceMm: 15.0,
      residualToleranceMm: 0.001,
      units: 'mm'
    });

    test(5, 'ICP Deterministic Alignment Convergence',
      icpRes.qualityReport.convergenceStatus === 'CONVERGED' && icpRes.qualityReport.finalRmseMm < 0.1,
      `ICP Converged in ${icpRes.qualityReport.iterationsCompleted} iterations with final RMSE: ${icpRes.qualityReport.finalRmseMm} mm`
    );

    // 6. Minimum Correspondence Validation & Degenerate Geometry Detection (Rule 9 & 10)
    const degenerateRes = RigidTransformSolver317.solveProcrustesSVD(correspondences.slice(0, 2));

    test(6, 'Degenerate Geometry Detection (Rule 9 & 10: Insufficient correspondences)',
      degenerateRes.degenerate && degenerateRes.reason?.includes('INSUFFICIENT_CORRESPONDENCES'),
      `Correctly rejected < 3 points with reason: ${degenerateRes.reason}`
    );

    // 7. Trimmed ICP Outlier Rejection (Rule 24)
    const noisySource = [...shiftedSource, { x: 500, y: 500, z: 500 }]; // Add far outlier
    const icpTrimmed = IterativeClosestPointSolver317.executeICP(noisySource, targetPoints, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'PAIRWISE',
      maxIterations: 30,
      outlierRejectionRatio: 0.15,
      maxCorrespondenceDistanceMm: 50.0,
      units: 'mm'
    });

    test(7, 'Trimmed ICP Outlier Rejection (Rule 24)',
      icpTrimmed.qualityReport.residualAnalysis.rejectedCorrespondenceCount > 0,
      `Trimmed ICP rejected ${icpTrimmed.qualityReport.residualAnalysis.rejectedCorrespondenceCount} outlier pairs.`
    );

    // 8. Insufficient Overlap Detection (Rule 39)
    const farSource: Point3D[] = [{ x: 1000, y: 1000, z: 1000 }, { x: 1050, y: 1000, z: 1000 }, { x: 1000, y: 1050, z: 1000 }];
    const icpFar = IterativeClosestPointSolver317.executeICP(farSource, targetPoints, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'PAIRWISE',
      maxCorrespondenceDistanceMm: 10.0,
      minOverlapRatio: 0.50,
      units: 'mm'
    });

    test(8, 'Insufficient Overlap Detection (Rule 39)',
      icpFar.qualityReport.convergenceStatus === 'INSUFFICIENT_OVERLAP',
      `Detected insufficient overlap status: ${icpFar.qualityReport.convergenceStatus}`
    );

    // 9. Full Residual Analysis Metrics (Rule 34 & 35)
    const resMetrics = icpRes.qualityReport.residualAnalysis;

    test(9, 'Full Residual Analysis Metrics (Rule 34 & 35)',
      resMetrics.meanResidualMm >= 0 && resMetrics.medianResidualMm >= 0 && resMetrics.percentile90ResidualMm !== undefined,
      `Mean: ${resMetrics.meanResidualMm}mm, Median: ${resMetrics.medianResidualMm}mm, P90: ${resMetrics.percentile90ResidualMm}mm`
    );

    // 10. Engine Full Lifecycle Execution (prepare -> initialize -> register -> refine -> validate -> commit)
    const plySample = `ply
format ascii 1.0
element vertex 6
property float x
property float y
property float z
property float intensity
end_header
0.0 0.0 0.0 100
50.0 0.0 0.0 110
50.0 50.0 0.0 120
0.0 50.0 0.0 130
25.0 25.0 40.0 140
10.0 20.0 15.0 150`;

    const rawA = this.importService.importPointCloud(plySample, 'scan_A.ply', 'PROJ-REG-317', 'REV-A');
    const rawB = this.importService.importPointCloud(plySample, 'scan_B.ply', 'PROJ-REG-317', 'REV-A');

    const session = this.registrationEngine.prepare([rawA], rawB, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'PAIRWISE',
      units: rawA.units
    });

    this.registrationEngine.initialize(session);
    this.registrationEngine.register(session, rawA.chunks[0].points, rawB.chunks[0].points);
    this.registrationEngine.refine(session, rawA.chunks[0].points, rawB.chunks[0].points);
    const registeredCloud = this.registrationEngine.commit(session, rawA.chunks[0].points, rawA.pointCloudId, 'REV-317-COMMIT');

    test(10, 'Engine Full Lifecycle (prepare -> init -> register -> refine -> commit)',
      registeredCloud !== undefined && session.status === 'COMMITTED',
      `Created RegisteredPointCloud ID: ${registeredCloud.registeredDatasetId}`
    );

    // 11. Point Provenance Retention (Rule 67 & 68: Original & Transformed Points)
    const firstPointRecord = registeredCloud.registeredPoints[0];

    test(11, 'Point Provenance Retention (Rule 67 & 68: Source dataset & original point retained)',
      firstPointRecord.sourceDatasetId === rawA.pointCloudId && firstPointRecord.originalPoint.x === 0.0,
      `Record retains sourceDatasetId: ${firstPointRecord.sourceDatasetId}, Original X: ${firstPointRecord.originalPoint.x}`
    );

    // 12. Evidence Bus Event Emission (Rule 93 & 94: REGISTRATION_COMPLETED)
    const evidenceList = this.evidenceBus.queryEvidence({ revisionId: 'REV-317-COMMIT' });
    const regEv = evidenceList.find(e => e.runId.startsWith('REG-ICP-') || e.metrics.outputDatasetId === registeredCloud.registeredDatasetId);

    test(12, 'Evidence Bus Event Emission (Rule 93 & 94: REGISTRATION_COMPLETED)',
      regEv !== undefined && regEv.metrics.algorithm === 'ICP_POINT_TO_POINT',
      `Registered Evidence ID: ${regEv?.evidenceId}`
    );

    // 13. Unit Mismatch Precondition Verification (Rule 55)
    const rawMeter = { ...rawA, units: 'm' as const };
    let caughtUnitErr = false;
    try {
      this.registrationEngine.prepare([rawMeter], rawB, { algorithm: 'ICP_POINT_TO_POINT', mode: 'PAIRWISE', units: 'm' });
    } catch (err: any) {
      caughtUnitErr = err.message.includes('PRECONDITION_FAILURE');
    }

    test(13, 'Unit Mismatch Precondition Rejection (Rule 55)',
      caughtUnitErr,
      'Caught Unit Mismatch exception on mismatched scan units.'
    );

    // 14. Matrix Composition (C = A * B)
    const trA = RigidTransformSolver317.buildTransform([1,0,0, 0,1,0, 0,0,1], [10, 0, 0]);
    const trB = RigidTransformSolver317.buildTransform([1,0,0, 0,1,0, 0,0,1], [0, 20, 0]);
    const trC = RigidTransformSolver317.multiplyTransforms(trA, trB);

    test(14, 'Rigid Transform Matrix Composition (C = A * B)',
      trC.translationVector[0] === 10 && trC.translationVector[1] === 20,
      `Composed transform translation: [${trC.translationVector.join(', ')}]`
    );

    // 15. GPU Truth Rule (Rule 83: CPU_SINGLE_THREAD logged accurately)
    test(15, 'GPU Truth Rule (Rule 83: Accurately log CPU execution)',
      registeredCloud.provenance.executionBackend === 'CPU_SINGLE_THREAD',
      `Execution backend accurately recorded as: ${registeredCloud.provenance.executionBackend}`
    );

    // 16. Multi-Scan Registration Graph Construction (Rule 41 & 44)
    const regGraph = this.registrationEngine.buildRegistrationGraph(
      [
        { id: 'SCAN-1', label: 'Front Scan', pose: trA },
        { id: 'SCAN-2', label: 'Side Scan', pose: trB },
        { id: 'SCAN-3', label: 'Back Scan', pose: trC }
      ],
      [
        { sourceId: 'SCAN-1', targetId: 'SCAN-2', transform: trA, rmseMm: 0.05 },
        { sourceId: 'SCAN-2', targetId: 'SCAN-3', transform: trB, rmseMm: 0.08 },
        { sourceId: 'SCAN-3', targetId: 'SCAN-1', transform: trC, rmseMm: 0.12 }
      ]
    );

    test(16, 'Multi-Scan Registration Graph (Rule 41 & 44)',
      regGraph.nodes.length === 3 && regGraph.edges.length === 3 && regGraph.loopClosureDetected,
      `Graph built with ${regGraph.nodes.length} nodes, ${regGraph.edges.length} edges, Loop Closure: ${regGraph.loopClosureDetected}`
    );

    // 17. Determinism & Reproducibility (Rule 80)
    const icpRes2 = IterativeClosestPointSolver317.executeICP(shiftedSource, targetPoints, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'FINE',
      maxIterations: 30,
      maxCorrespondenceDistanceMm: 15.0,
      residualToleranceMm: 0.001,
      units: 'mm'
    });

    test(17, 'Determinism & Reproducibility (Rule 80)',
      icpRes.qualityReport.finalRmseMm === icpRes2.qualityReport.finalRmseMm,
      `Identical final RMSE (${icpRes.qualityReport.finalRmseMm} mm) across independent runs.`
    );

    // 18. Alignment != Fusion != Mesh (Rule 73, 74, 75)
    test(18, 'Boundary Rule (Rule 73, 74, 75: Alignment != Mesh / CAD)',
      registeredCloud.globalCoordinateFrame === 'GLOBAL_ALIGNMENT_FRAME' && registeredCloud.pointCount === rawA.chunks[0].points.length,
      `Registration output contains ${registeredCloud.pointCount} aligned points without premature mesh generation.`
    );

    // 19. Digital Thread Integration (Rule 97)
    test(19, 'Digital Thread Integration (Rule 97)',
      registeredCloud.provenance.sourceDatasetId === rawA.pointCloudId && registeredCloud.provenance.targetDatasetId === rawB.pointCloudId,
      `Provenances links Source dataset (${registeredCloud.provenance.sourceDatasetId}) to Target (${registeredCloud.provenance.targetDatasetId})`
    );

    // 20. Synthetic 100-Point Cloud Scalability
    const largeTarget: Point3D[] = Array.from({ length: 100 }).map((_, i) => ({
      x: (i % 10) * 10,
      y: Math.floor(i / 10) * 10,
      z: Math.sin(i * 0.1) * 5
    }));
    const largeSource: Point3D[] = largeTarget.map(p => ({ x: p.x + 0.5, y: p.y - 0.5, z: p.z + 0.2 }));

    const tStart = performance.now();
    const largeRes = IterativeClosestPointSolver317.executeICP(largeSource, largeTarget, {
      algorithm: 'ICP_POINT_TO_POINT',
      mode: 'PAIRWISE',
      maxIterations: 20,
      units: 'mm'
    });
    const tDuration = performance.now() - tStart;

    test(20, 'Large Point Cloud Scalability Benchmark',
      largeRes.qualityReport.convergenceStatus === 'CONVERGED' && tDuration < 1000,
      `Registered 100 points in ${tDuration.toFixed(2)} ms with RMSE: ${largeRes.qualityReport.finalRmseMm} mm`
    );

    const passedCount = results.filter(r => r.passed).length;
    const failedCount = results.filter(r => !r.passed).length;

    return {
      passed: failedCount === 0,
      totalAssertions: results.length,
      passedCount,
      failedCount,
      results
    };
  }
}
